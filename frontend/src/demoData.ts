// Универсальный формат для read-only показа «портфолио / профиля» автора объявления.
export interface DemoDir {
  name: string
  icon: string
  exp?: string        // опыт в направлении
  chips?: string[]    // навыки / виды работ
  crops?: string[]    // культуры (агро)
}
export interface DemoProfile {
  id: string
  role: 'operator' | 'company' | 'customer'
  photo: string       // файл в /portfolio (лицо или логотип)
  square?: boolean    // логотип квадратный
  name: string
  sub: string         // категория / юрформа
  loc: string
  rating?: string     // публичный рейтинг (компания)
  docs: string[]      // бейджи документов
  expTotal?: string   // общий стаж
  fleet?: string      // парк (компания)
  about: string
  dirs: DemoDir[]
  links?: string
  pay?: string
  isPrivate?: boolean // заказчик — приватный профиль
}

